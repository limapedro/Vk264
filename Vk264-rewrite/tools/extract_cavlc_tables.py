"""Extract x264 CAVLC VLC tables from common/tables.c into a standalone C header.

Usage: python extract_cavlc_tables.py <x264 tables.c> <output header>
The generated header is checked in so the encoder never depends on x264 sources.
"""
import re
import sys
from pathlib import Path

TABLES = [
    ("x264_coeff0_token",        "vk_coeff0_token",        "6"),
    ("x264_coeff_token",         "vk_coeff_token",         "6][16][4"),
    ("x264_total_zeros",         "vk_total_zeros",         "15][16"),
    ("x264_total_zeros_2x2_dc",  "vk_total_zeros_2x2_dc",  "3][4"),
    ("x264_run_before_init",     "vk_run_before_init",     "7][16"),
]

def extract(src: str, name: str):
    m = re.search(r"const\s+vlc_t\s+" + re.escape(name) + r"\s*\[[^\]]*\]"
                  r"(?:\[[^\]]*\])*\s*=\s*\{", src)
    if not m:
        raise SystemExit(f"table {name} not found")
    i = m.end() - 1
    depth = 0
    for j in range(i, len(src)):
        if src[j] == '{': depth += 1
        elif src[j] == '}':
            depth -= 1
            if depth == 0:
                return src[i:j+1]
    raise SystemExit(f"unterminated table {name}")

def tokenize(body):
    body = re.sub(r"/\*.*?\*/", " ", body, flags=re.S)
    body = re.sub(r"//[^\n]*", " ", body)
    return re.findall(r"\{|\}|0x[0-9A-Fa-f]+|-?\d+|,", body)

def parse(body):
    tokens = tokenize(body)
    pos = 0
    def value():
        nonlocal pos
        t = tokens[pos]
        if t == '{':
            pos += 1
            items = []
            while tokens[pos] != '}':
                if tokens[pos] == ',':
                    pos += 1
                    continue
                items.append(value())
            pos += 1
            return items
        pos += 1
        return int(t, 0) if t.startswith('0x') else int(t)
    return value()

def emit(v, indent=0):
    pad = "    " * indent
    if isinstance(v, list):
        # A list of 2-integer pairs is a vlc_t entry: keep it on one line.
        if v and all(isinstance(x, int) for x in v) and len(v) == 2:
            return f"{{{v[0]}, {v[1]}}}"
        out = [pad + "{"]
        for item in v:
            out.append(pad + "    " + emit(item, indent + 1).lstrip() + ",")
        out.append(pad + "}")
        return "\n".join(out)
    return str(v)

src = Path(sys.argv[1]).read_text(encoding="utf-8")
out = ["/* Generated by tools/extract_cavlc_tables.py from x264 common/tables.c.",
       " * SPDX-License-Identifier: GPL-2.0-or-later */",
       "#ifndef VK264_CAVLC_TABLES_H", "#define VK264_CAVLC_TABLES_H", "",
       "typedef struct { unsigned char i_bits, i_size; } vk_vlc_t;", ""]
for xname, cname, dims in TABLES:
    tree = parse(extract(src, xname))
    out.append(f"static const vk_vlc_t {cname}[{dims}] =")
    out.append(emit(tree) + ";")
    out.append("")
out.append("#endif")
Path(sys.argv[2]).write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {sys.argv[2]}")
