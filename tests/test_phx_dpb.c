/* Blob-aware readers (two goldens in one translation unit). */
static int rdi(const unsigned char *g, size_t *pos)
{
    int v; memcpy(&v, g + *pos, sizeof(v)); *pos += sizeof(v); return v;
}
static const unsigned char *tk(const unsigned char *g, size_t *pos, size_t n)
{
    const unsigned char *p = g + *pos; *pos += n; return p;
}

static int check_golden(const unsigned char *g, size_t len, int frame_num,
                        int slice_type, const char *label)
{
    size_t pos = 0;
    int mbw = rdi(g, &pos), mbh = rdi(g, &pos);
    (void)rdi(g, &pos); (void)rdi(g, &pos);      /* x264 fdec strides */
    int w = rdi(g, &pos), h = rdi(g, &pos);
    int alpha = rdi(g, &pos), beta = rdi(g, &pos), coff = rdi(g, &pos);
    int bcabac = rdi(g, &pos);
    int mbn = mbw*mbh;
    const unsigned char *pre_y  = tk(g, &pos, (size_t)w*h);
    const unsigned char *pre_uv = tk(g, &pos, (size_t)w*h/2);
    const unsigned char *post_y = tk(g, &pos, (size_t)w*h);
    const unsigned char *post_uv= tk(g, &pos, (size_t)w*h/2);
    const unsigned char *type   = tk(g, &pos, mbn);
    const unsigned char *nnz    = tk(g, &pos, (size_t)mbn*48);
    const unsigned char *cbpb   = tk(g, &pos, (size_t)mbn*2);
    const unsigned char *xf     = tk(g, &pos, mbn);
    const unsigned char *ref0   = tk(g, &pos, (size_t)mbn*4);
    const unsigned char *ref1   = tk(g, &pos, (size_t)mbn*4);
    const unsigned char *mv0    = tk(g, &pos, (size_t)mbn*16*4);
    const unsigned char *mv1    = tk(g, &pos, (size_t)mbn*16*4);
    const unsigned char *qp8    = tk(g, &pos, mbn);
    tk(g, &pos, mbn);                            /* partition (unused) */
    const unsigned char *slt    = tk(g, &pos, (size_t)mbn*4);
    const unsigned char *fld    = tk(g, &pos, mbn);
    if (pos != len || alpha || beta || coff) {
        printf("%s: bad golden header/length\n", label); return 1;
    }

    phx_mb_state_t *s = phx_mb_state_new(mbw, mbh);
    int *qp = (int *)malloc((size_t)mbn * sizeof(int));
    uint8_t *fdec_y = (uint8_t *)malloc((size_t)w*h);
    phx_dpb_t *d = phx_dpb_create(w, h, 0);
    if (!s || !qp || !fdec_y || !d) { printf("%s: OOM\n", label); return 1; }
    for (int i = 0; i < mbn; i++) {
        s->type[i] = type[i];
        memcpy(s->non_zero_count[i], nnz + (size_t)i*48, 48);
        memcpy(&s->cbp[i], cbpb + (size_t)i*2, 2);
        s->mb_transform_size[i] = xf[i];
        memcpy(s->ref[0] + i*4, ref0 + i*4, 4);
        memcpy(s->ref[1] + i*4, ref1 + i*4, 4);
        memcpy(s->mv[0] + i*16, mv0 + (size_t)i*16*4, (size_t)16*4);
        memcpy(s->mv[1] + i*16, mv1 + (size_t)i*16*4, (size_t)16*4);
        int32_t v; memcpy(&v, slt + i*4, 4);
        s->slice_table[i] = (uint8_t)v;
        s->field[i] = fld[i];
        qp[i] = qp8[i];
    }
    s->slice_type = slice_type;                  /* 2=I, 0=P */
    s->b_cabac = bcabac;
    s->b_transform_8x8_mode = 1;
    s->b_interlaced = 0;
    memcpy(fdec_y, pre_y, (size_t)w*h);

    phx_dpb_store_params_t p;
    memset(&p, 0, sizeof(p));
    p.fdec_y = fdec_y; p.fdec_y_stride = w;
    p.fdec_uv = pre_uv; p.fdec_uv_stride = w;     /* NV12 row bytes */
    p.mb_state = s; p.qp_array = qp; p.qp = 26;
    p.b_cabac = bcabac;
    p.frame_num = frame_num; p.poc = 2*frame_num;
    p.display_frame = frame_num;
    p.i_type = slice_type == 2 ? 2 : 1;
    p.b_kept_as_ref = 1;
    int rc = phx_dpb_store_frame(d, &p);
    const phx_frame_t *r = phx_dpb_get_ref(d, frame_num);
    int bad = 0;
    if (rc || !r) { printf("%s: store/get failed rc=%d\n", label, rc); bad = 1; }
    else {
        int dy = 0, dc = 0, chy = 0, chc = 0;
        for (int i = 0; i < w*h; i++) {
            if (pre_y[i] != post_y[i]) chy++;
            if (r->plane[i/w*r->i_stride + i%w] != post_y[i]) dy++;
        }
        for (int i = 0; i < w*h/2; i++) {
            if (pre_uv[i] != post_uv[i]) chc++;
            if (r->plane_chroma[i/w*r->i_stride_planes[1] + i%w] != post_uv[i]) dc++;
        }
        printf("%s: x264 deblock changed luma=%d chroma=%d; "
               "Phoenix diff luma=%d chroma=%d\n", label, chy, chc, dy, dc);
        for (int i = 0; i < w*h-3; i++)
            if (pre_y[i] != post_y[i]) {
                int y = i/w, x = i%w;
                printf("  first deblocked luma (x=%d,y=%d): raw=%d,%d,%d,%d "
                       "x264=%d,%d,%d,%d phx=%d,%d,%d,%d\n", x, y,
                       pre_y[i],pre_y[i+1],pre_y[i+2],pre_y[i+3],
                       post_y[i],post_y[i+1],post_y[i+2],post_y[i+3],
                       r->plane[y*r->i_stride+x], r->plane[y*r->i_stride+x+1],
                       r->plane[y*r->i_stride+x+2], r->plane[y*r->i_stride+x+3]);
                break;
            }
        /* frame.c:541/548 — a stored reference carries replicated pads. */
        if (r->plane[-1] != r->plane[0] ||
            r->plane[-r->i_stride] != r->plane[0]) {
            printf("%s: luma border mismatch\n", label); bad = 1;
        }
        if (dy || dc) bad = 1;
    }
    phx_dpb_free(d); free(fdec_y); free(qp);
    phx_mb_state_delete(s);
    return bad;
}

static int check_api(void)
{
    int bad = 0;
    if (phx_dpb_create(30, 32, 0) != NULL) { printf("bad geometry accepted\n"); bad=1; }
    phx_dpb_t *d = phx_dpb_create(32, 32, 0);
    if (!d) { printf("create failed\n"); return 1; }
    if (phx_dpb_count(d) != 0 || phx_dpb_get_ref(d, 0) != NULL ||
        phx_dpb_get_ref_l0(d, 0) != NULL) { printf("empty DPB not empty\n"); bad=1; }
    phx_dpb_store_params_t p;
    memset(&p, 0, sizeof(p));
    if (phx_dpb_store_frame(d, &p) == 0) { printf("NULL store accepted\n"); bad=1; }
    phx_dpb_reset(d);
    if (phx_dpb_count(d) != 0) { printf("reset failed\n"); bad=1; }
    if (phx_dpb_remove_poc(d, 0) != 0) { printf("empty remove failed\n"); bad=1; }
    phx_dpb_free(d);
    phx_dpb_free(NULL);
    return bad;
}

int main(void)
{
    int bad = check_golden(golden_f0, sizeof(golden_f0), 0, 2, "GOLDEN I") |
              check_golden(golden_f1, sizeof(golden_f1), 1, 0, "GOLDEN P") |
              check_api();
    printf("phx_dpb: %s\n", bad ? "FAIL" : "PASS");
    return bad;
}
