#!/usr/bin/env python3
"""Generate docs/FUNCTION_INVENTORY.md from the vendored x264 source.

Scans reference/x264 for C function definitions, cross-references src/ (the
Phoenix port) for identically-named functions, and groups by x264 module.
The result is a mechanical, evidence-backed inventory.
"""
import pathlib, re, collections
R=pathlib.Path(__file__).resolve().parents[1]
X=R/'reference/x264'
O=R/'src'
KEYWORDS={'if','for','while','switch','return','sizeof','do','else','case',
          'typedef','struct','enum','union','static','const','inline','void'}

def defs(path):
    out=[]
    lines=path.read_text(encoding='utf-8',errors='replace').splitlines()
    for i,l in enumerate(lines):
        s=l.strip()
        if not s or s.startswith('#') or s.startswith('//') or s.endswith(';'):
            continue
        if '(' not in s or ')' not in s:
            continue
        # Collect a multi-line signature: keep going until a line is `{`.
        j, head = i, s
        while j < len(lines) and lines[j].strip() != '{':
            j += 1
            if j-i > 6 or j >= len(lines): break
            head += ' ' + lines[j].strip()
        if j >= len(lines) or lines[j].strip() != '{': continue
        head = head.split('(')[0].strip()
        m = re.findall(r'[A-Za-z_]\w*', head)
        if not m or len(m) < 2: continue
        name = m[-1]
        if name in KEYWORDS or len(name) < 3: continue
        out.append((name, i+1, ' '.join(head.split())))
    return out

xrows=[]
for f in sorted(list(X.rglob('*.c'))+list(X.rglob('*.h'))):
    if any(p in f.parts for p in ('tools','filters','input','output','extras')): continue
    for name,line,text in defs(f):
        xrows.append((str(f.relative_to(X)).replace('\\','/'),line,name,text))

def canon(name):
    """Drop the project prefix so phx_foo matches x264_foo."""
    for p in ('phx_', 'x264_'):
        if name.startswith(p):
            return name[len(p):]
    return name

onames={}
LIBC={'malloc','free','memcpy','memset','printf','fprintf','realloc','strlen'}
for f in sorted(O.rglob('*.c'))+sorted(O.rglob('*.h')):
    for name,line,text in defs(f):
        key = canon(name)
        if key in LIBC: continue
        onames.setdefault(key,[]).append(f.name)

groups=collections.defaultdict(list)
for path,line,name,text in xrows:
    mod=path.split('/')[0] if '/' in path else 'root'
    groups[mod].append((path,line,name,text))

lines=[
 '# Phoenix function inventory (mechanical extract from the vendored x264 source)',
 '',
 'Source: `reference/x264/` (copy of the exact reference build used',
 'for all parity measurements). Phoenix port side: `src/`.',
 'Generated by `tools/gen_function_inventory.py`; re-run after porting a function.',
 '',
 'Legend: **PORTED** = same-named function exists in `src/` (still needs its',
 'unit test and parity gate to be trusted); **MISSING** = not ported yet.',
 '',
 f'Total x264 C functions indexed: **{len(xrows)}**.',
 '',
]
for mod in sorted(groups):
    rows=groups[mod]
    lines += [f'## {mod} ({len(rows)} functions)','',
              '| x264 function | source:line | phoenix | signature / note |',
              '|---|---:|---|---|']
    for path,line,name,text in rows:
        status='PORTED' if canon(name) in onames else 'MISSING'
        note=text.replace('|','\\|')[:140]
        lines.append(f'| `{name}` | `{path}:{line}` | **{status}** | {note} |')
    lines.append('')
(R/'docs').mkdir(parents=True,exist_ok=True)
(R/'docs/FUNCTION_INVENTORY.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('wrote FUNCTION_INVENTORY.md with',len(xrows),'functions; phoenix names',len(onames))
