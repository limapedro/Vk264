#!/usr/bin/env python3
"""Generate src/phx_tables.{h,c} mechanically from the authoritative x264 source.

Source lines are recorded in the generated header; never edit generated files.
Only the eight-bit configuration is emitted (the parity reference build uses
8-bit 4:2:0), so preprocessor-guarded 10/12-bit table entries are skipped.
"""
import pathlib, re

R = pathlib.Path(__file__).resolve().parents[1]
T = R / 'reference/x264/common/tables.c'
B = R / 'reference/x264/common/bitstream.h'
M = R / 'reference/x264/common/macroblock.h'


def body(text, name):
    i = text.index(name)
    i = text.index('{', i)
    depth, j = 0, i
    while True:
        if text[j] == '{': depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0: break
        j += 1
    s = text[i+1:j]
    s = re.sub(r'/\*.*?\*/', '', s, flags=re.S)
    s = re.sub(r'//[^\n]*', '', s)
    return s


def nums(text, name):
    return [int(x) for x in re.findall(r'-?\d+', body(text, name))]


def chroma_base():
    s = body(M.read_text(encoding='utf-8'), 'i_chroma_qp_table')
    out, skip = [], 0
    for line in s.splitlines():
        t = line.strip()
        if t.startswith('#if'): skip += 1; continue
        if t.startswith('#endif'): skip -= 1; continue
        if skip or t.startswith('#'): continue
        out += [int(n) for n in re.findall(r'QP\((-?\d+)\)', t) or re.findall(r'-?\d+', t)]
    return out


t = T.read_text(encoding='utf-8')
b = B.read_text(encoding='utf-8')
lam = nums(t, 'x264_lambda_tab')
lam2 = nums(t, 'x264_lambda2_tab')
# The inter row in x264's source has only 76 initializers; C zero-fills the
# last 6. Preserve that quirk exactly (do not "fix" it).
tl_body = body(t, 'x264_trellis_lambda2_tab')
tl_rows = [[int(x) for x in re.findall(r'-?\d+', part)]
           for part in tl_body.split('},') if re.findall(r'-?\d+', part)]
assert len(tl_rows) == 2 and len(tl_rows[0]) == 76 and len(tl_rows[1]) == 82, \
       [len(r) for r in tl_rows]
tl = tl_rows[0] + [0]*6 + tl_rows[1]
off = nums(t, 'x264_chroma_lambda2_offset_tab')
ue = nums(b, 'x264_ue_size_tab')
ch = chroma_base()
assert len(lam) == 82 and len(lam2) == 82 and len(tl) == 164
assert len(off) == 37 and len(ue) == 256 and len(ch) == 76, (len(off), len(ue), len(ch))


def fmt(vals, per=8, cast=''):
    rows = [', '.join((cast + str(v)) for v in vals[i:i+per]) + ','
            for i in range(0, len(vals), per)]
    return '\n    ' + '\n    '.join(rows)


hdr = f'''/* GENERATED by tools/gen_tables.py — do not edit.
 * Source: reference/x264/common/tables.c:97,114,131,168;
 *         reference/x264/common/bitstream.h:201;
 *         reference/x264/common/macroblock.h:249 (8-bit entries only).
 * SHADER: A — immutable lookup tables, can live in constant memory.
 */
#ifndef PHX_TABLES_H
#define PHX_TABLES_H
#include <stdint.h>

#define PHX_QP_MAX_SPEC 51
#define PHX_QP_MAX 69
#define PHX_QP_MAX_MAX 81
#define PHX_LOOKAHEAD_QP 12
#define PHX_MAX_CHROMA_LAMBDA_OFFSET 36
#define PHX_CHROMA_QP_BASE_OFFSET 12

extern const uint16_t phx_lambda_tab[PHX_QP_MAX_MAX+1];
extern const int phx_lambda2_tab[PHX_QP_MAX_MAX+1];
extern const int phx_trellis_lambda2_tab[2][PHX_QP_MAX_MAX+1];
extern const uint16_t phx_chroma_lambda2_offset_tab[PHX_MAX_CHROMA_LAMBDA_OFFSET+1];
extern const uint8_t phx_ue_size_tab[256];
extern const uint8_t phx_chroma_qp_base[{len(ch)}];
#endif
'''
src = f'''/* GENERATED by tools/gen_tables.py — do not edit. */
#include "phx_tables.h"

const uint16_t phx_lambda_tab[] ={{{fmt(lam)}}};
const int phx_lambda2_tab[] ={{{fmt(lam2)}}};
const int phx_trellis_lambda2_tab[2][PHX_QP_MAX_MAX+1] = {{
    {{{fmt(tl[:82], cast='')}
    }},
    {{{fmt(tl[82:], cast='')}
    }}
}};
const uint16_t phx_chroma_lambda2_offset_tab[] ={{{fmt(off)}}};
const uint8_t phx_ue_size_tab[] ={{{fmt(ue, per=16)}}};
const uint8_t phx_chroma_qp_base[] ={{{fmt(ch)}}};
'''
(R/'src/phx_tables.h').write_text(hdr, encoding='utf-8')
(R/'src/phx_tables.c').write_text(src, encoding='utf-8')
print('generated phx_tables.h/.c:', len(lam), len(lam2), len(tl), len(off), len(ue), len(ch))
