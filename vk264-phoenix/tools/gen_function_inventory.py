#!/usr/bin/env python3
"""Generate docs/phoenix/FUNCTION_INVENTORY.md from the vendored x264 source.

Scans vk264-phoenix/reference/x264 for C function definitions, cross-references
Vk264-rewrite/src/ref for an identically-named oracle function, and groups by
x264 module. The result is a mechanical, evidence-backed inventory.
"""
import pathlib, re, collections
R=pathlib.Path(__file__).resolve().parents[1]
X=R/'reference/x264'
O=R.parent/'Vk264-rewrite/src/ref'
KEYWORDS={'if','for','while','switch','return','sizeof','do','else','case',
          'typedef','struct','enum','union','static','const','inline','void'}

def defs(path):
    out=[]
    lines=path.read_text(encoding='utf-8',errors='replace').splitlines()
    for i,l in enumerate(lines):
        s=l.strip()
        if not s or s.startswith('#') or s.startswith('//') or s.endswith(';'):
            continue
        if '(' not in s or ')' not in s:
            continue
        # next non-empty line must open a function body
        j=i+1
        while j<len(lines) and not lines[j].strip(): j+=1
        if j>=len(lines) or lines[j].strip()!='{': continue
        head=s.split('(')[0].strip()
        m=re.findall(r'[A-Za-z_]\w*',head)
        if not m: continue
        name=m[-1]
        if name in KEYWORDS: continue
        # must look like a function head (has a return type before the name)
        if len(m)<2: continue
        out.append((name,i+1,s))
    return out

xrows=[]
for f in sorted(X.rglob('*.c')):
    if any(p in f.parts for p in ('tools','filters','input','output','extras')): continue
    for name,line,text in defs(f):
        xrows.append((str(f.relative_to(X)).replace('\\','/'),line,name,text))

onames={}
for f in sorted(O.rglob('*.c'))+sorted(O.rglob('*.h')):
    for name,line,text in defs(f):
        onames.setdefault(name,[]).append(f.name)

groups=collections.defaultdict(list)
for path,line,name,text in xrows:
    mod=path.split('/')[0] if '/' in path else 'root'
    groups[mod].append((path,line,name,text))

lines=[
 '# Phoenix function inventory (mechanical extract from the vendored x264 source)',
 '',
 'Source: `reference/x264/` (copy of the exact reference build used',
 'for all parity measurements). Oracle side: `Vk264-rewrite/src/ref/`.',
 'Generated by `tools/gen_function_inventory.py`; re-run after updating the reference.',
 '',
 'Legend: **ORACLE** = same-named function exists in the current oracle;',
 '**MISSING** = no same-named function (a genuine porting candidate);',
 '**CHECK** = present but needs a parity audit before it can be trusted.',
 '',
 f'Total x264 C functions indexed: **{len(xrows)}**.',
 '',
]
for mod in sorted(groups):
    rows=groups[mod]
    lines += [f'## {mod} ({len(rows)} functions)','',
              '| x264 function | source:line | oracle | signature / note |',
              '|---|---:|---|---|']
    for path,line,name,text in rows:
        if name in onames: status='ORACLE' if name.startswith('x264_') is False else 'CHECK'
        else: status='MISSING'
        note=text.replace('|','\\|')[:140]
        lines.append(f'| `{name}` | `{path}:{line}` | **{status}** | {note} |')
    lines.append('')
(R/'docs').mkdir(parents=True,exist_ok=True)
(R/'docs/FUNCTION_INVENTORY.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('wrote FUNCTION_INVENTORY.md with',len(xrows),'functions; oracle names',len(onames))
